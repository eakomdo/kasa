/**
 * In-browser database for the mock backend. Mirrors the tables the Django
 * backend will have; persisted to localStorage so demos survive reloads.
 * Bump DB_VERSION whenever the shape or seed data changes.
 */
import type {
  BadgeId,
  CommunityKind,
  CommunityRole,
  JoinPolicy,
  NotificationKind,
  ReportAction,
  ReportReason,
  Role,
  User,
} from '@/shared/api/schemas';
import { safeStorage } from '@/shared/lib/misc';
import { seedCommunity } from './data/community';
import { seedPeople, seedLearning } from './data/people';

export const DB_VERSION = 4;
const STORAGE_KEY = 'kasa-mock-db';

export interface DbUser extends User {
  password: string;
  lastActiveAt: string;
}

export interface DbProgress {
  mastery: number;
  nextReviewAt: string;
  lastSeenAt: string;
}

export interface DbThread {
  id: string;
  communityId: string;
  title: string;
  body: string;
  authorId: string;
  lang: 'twi' | 'ga' | null;
  tags: string[];
  createdAt: string;
  lastActivityAt: string;
  pinned: boolean;
  locked: boolean;
  status: 'visible' | 'removed';
  acceptedReplyId: string | null;
  /** Votes from people not in the db, so seeded threads look lived-in */
  baseScore: number;
}

export interface DbCommunity {
  id: string;
  slug: string;
  name: string;
  description: string;
  kind: CommunityKind;
  official: boolean;
  lang: 'twi' | 'ga' | null;
  bands: Array<'lp' | 'up' | 'jhs' | 'shs'>;
  joinPolicy: JoinPolicy;
  joinCode: string; // e.g. "ASF-7B"; regenerated by managers
  status: 'pending' | 'active' | 'rejected' | 'archived';
  color: 'forest' | 'gold' | 'clay' | 'sky';
  school: string | null;
  region: string | null;
  rules: string[];
  staffOnlyPosting: boolean;
  createdById: string;
  createdAt: string;
  reviewNote: string | null;
  reviewedById: string | null;
}

export interface DbMembership {
  communityId: string;
  userId: string;
  role: CommunityRole | null; // null while pending
  status: 'member' | 'pending';
  joinedAt: string | null;
  requestedAt: string | null;
  requestNote: string | null;
}

export interface DbNotification {
  id: string;
  userId: string;
  kind: NotificationKind;
  title: string;
  body: string;
  href: string | null;
  createdAt: string;
  read: boolean;
}

export interface DbReply {
  id: string;
  threadId: string;
  authorId: string;
  body: string;
  createdAt: string;
  status: 'visible' | 'removed';
  baseScore: number;
}

export interface DbReport {
  id: string;
  targetType: 'thread' | 'reply';
  targetId: string;
  reason: ReportReason;
  note: string;
  reporterId: string;
  createdAt: string;
  status: 'open' | 'resolved' | 'dismissed';
  resolution: string | null;
  action: ReportAction | null;
}

export interface DbSuggestion {
  id: string;
  lang: 'twi' | 'ga';
  query: string;
  currentTranslation: string | null;
  suggestion: string;
  submittedById: string;
  supporters: number;
  createdAt: string;
  status: 'pending' | 'approved' | 'rejected';
}

/** Translations approved by moderators; lookup treats them as teacher-verified. */
export interface DbVerifiedTranslation {
  lang: 'twi' | 'ga';
  english: string;
  translation: string;
}

export interface Db {
  version: number;
  users: DbUser[];
  sessions: Record<string, string>; // token -> userId
  progress: Record<string, Record<string, DbProgress>>; // userId -> itemId -> progress
  activity: Record<string, Record<string, { count: number; xp: number }>>; // userId -> day -> totals
  badges: Record<string, Array<{ id: BadgeId; earnedAt: string }>>;
  processedAttempts: Record<string, { itemId: string; mastery: number; nextReviewAt: string }>; // clientId -> result
  communities: DbCommunity[];
  memberships: DbMembership[];
  notifications: DbNotification[];
  threads: DbThread[];
  replies: DbReply[];
  votes: Record<string, -1 | 0 | 1>; // `${userId}:${thread|reply}:${id}`
  reports: DbReport[];
  suggestions: DbSuggestion[];
  verifiedTranslations: DbVerifiedTranslation[];
}

function seed(): Db {
  const now = new Date();
  const users = seedPeople(now);
  const learning = seedLearning(now);
  return {
    version: DB_VERSION,
    users,
    sessions: {},
    ...learning,
    processedAttempts: {},
    ...seedCommunity(now),
    verifiedTranslations: [],
  };
}

let db: Db | null = null;

export function getDb(): Db {
  if (db) return db;
  const stored = safeStorage.get<Db | null>(STORAGE_KEY, null);
  db = stored && stored.version === DB_VERSION ? stored : seed();
  return db;
}

export function saveDb(): void {
  if (db) safeStorage.set(STORAGE_KEY, db);
}

/** Wipe and reseed; used by tests and the "reset demo" control. */
export function resetDb(): Db {
  db = seed();
  saveDb();
  return db;
}

export const isStaff = (role: Role) => role === 'moderator' || role === 'admin';
